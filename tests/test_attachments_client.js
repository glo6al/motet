// Execute the actual page client with no browser/storage/network authority.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../src/web/index.html'),'utf8');
const source=html.slice(html.indexOf('function createAttachmentsClient('),html.indexOf('/* end Attachments demo client */'));
const create=vm.runInNewContext(source+';createAttachmentsClient',{URLSearchParams});
const plain=v=>JSON.parse(JSON.stringify(v));
(async()=>{
  const {createAttachmentsFixture}=await import('../docs/fixtures/attachments/fixture.mjs');
  const poison=new Proxy({}, {get(){throw Error('disabled client touched adapter');}});
  for(const options of [{},{search:'?demo'},{enabled:true},{enabled:1,search:'?demo'},{enabled:true,search:'?notdemo=1'}]){
    const client=create({...options,fixture:poison});
    assert.equal(client.enabled,false);
    assert.equal(client.snapshot().destination,null);
    assert.equal(client.snapshot().filesCount,0);
    assert.equal(client.snapshot().lastAction,null);
    assert.equal(client.snapshot().management,null);
    assert.throws(()=>client.selectScenario('a03-one'),/not enabled/);
    assert.throws(()=>client.act({type:'send_sample'}),/not enabled/);
  }
  assert.throws(()=>create({enabled:true,search:'?demo'}),/fixture is required/);
  assert.throws(()=>create({enabled:true,search:'?demo',fixture:{schemaVersion:1,fixture:false,enabled:true}}),/fixture is required/);
  const fixture=createAttachmentsFixture({enabled:true,search:'?demo',scenario:'a03-five'});
  const client=create({enabled:true,search:'?demo',fixture});
  assert.equal(client.enabled,true);
  let snapshot=client.snapshot();
  assert.equal(snapshot.draft.fileIds.length,5);
  snapshot.files[0].name='not persistent';
  assert.notEqual(client.snapshot().files[0].name,'not persistent');
  snapshot=client.snapshot();
  const bind={draftId:snapshot.draft.id,destination:plain(snapshot.draft.destination),revision:snapshot.draft.revision,writerGeneration:snapshot.draft.writerGeneration};
  const removed=snapshot.draft.fileIds[0], kept=snapshot.draft.fileIds.slice(1);
  const after=client.act({...bind,type:'remove_file',fileId:removed});
  assert.deepEqual(plain(after.draft.fileIds),plain(kept));
  assert.equal(after.draft.text,snapshot.draft.text);
  assert.throws(()=>client.act({...bind,type:'send_sample'}));
  client.selectScenario('a06-unknown');
  assert.equal(client.snapshot().messages[0].state,'delivery_unknown');
  assert.equal(client.snapshot().messages[0].recovery.canFinish,false);
  const draftCommand=(type,extra={})=>{
    const d=client.snapshot().draft;
    return {type,draftId:d.id,destination:plain(d.destination),revision:d.revision,writerGeneration:d.writerGeneration,...extra};
  };
  const messageCommand=type=>{
    const m=client.snapshot().messages[0];
    return {type,messageId:m.id,requestId:m.requestId,destination:plain(m.destination),revision:m.revision,operationGeneration:m.operationGeneration};
  };
  client.selectScenario('a04-folder');
  let d=client.snapshot().draft;
  const text=d.text;
  client.act(draftCommand('retry_preparation',{fileId:d.fileIds[0]}));
  assert.equal(client.snapshot().draft.text,text);
  assert.equal(client.snapshot().lastAction.outcome,'preparation_ready');
  assert.equal(client.snapshot().draft.canSend,false);
  client.selectScenario('a05-conflict');
  d=client.snapshot().draft;
  const resumed=client.act(draftCommand('resume_draft'));
  assert.equal(resumed.draft.id,d.id);
  assert.notEqual(resumed.draft.writerGeneration,d.writerGeneration);
  assert.deepEqual(plain(resumed.draft.fileIds),plain(d.fileIds));
  client.selectScenario('a05-missing');
  const unavailable=client.snapshot().draft;
  const fresh=client.act(draftCommand('create_draft'));
  assert.notEqual(fresh.draft.id,unavailable.id);
  assert.equal(fresh.draft.text,'');assert.deepEqual(plain(fresh.draft.fileIds),[]);
  client.selectScenario('a06-unknown');
  const unknownDraft=plain(client.snapshot().draft), check=messageCommand('check_status');
  assert.equal(client.act(check).messages[0].state,'delivery_unknown');
  assert.deepEqual(plain(client.snapshot().draft),unknownDraft);
  const checked=plain(client.snapshot());
  assert.throws(()=>client.act(check));
  assert.deepEqual(plain(client.snapshot()),checked);
  client.selectScenario('a06-partial');
  assert.equal(client.snapshot().filesCount,1,'partial delivery counts only the materialized association');
  const original=plain(client.snapshot().messages[0]), currentDraft=plain(client.snapshot().draft);
  const finish=messageCommand('finish_send');
  const queued=client.act(finish);
  assert.equal(queued.messages.length,1);
  assert.equal(queued.filesCount,2,'Finish counts both associations on the same retained request');
  assert.equal(queued.messages[0].requestId,original.requestId);
  assert.equal(queued.messages[0].state,'queued');
  assert.deepEqual(plain(queued.messages[0].fileIds),original.fileIds);
  assert.deepEqual(plain(queued.draft),currentDraft);
  assert.throws(()=>client.act(finish));
  client.selectScenario('a06-partial');
  const cleaned=client.act(messageCommand('delete_saved_copies'));
  assert.equal(cleaned.messages[0].state,'not_sent');
  assert.equal(cleaned.messages[0].deliveryPhase,'cleanup_fenced');
  assert.equal(cleaned.deleteDialog,null);
  assert.equal(cleaned.filesCount,1,'workspace-only cleanup retains the counted association');
  assert.throws(()=>client.act(messageCommand('finish_send')));
  // Compatibility projections preserve typed data/authority; these are fictional client checks, not DOM or bytes.
  client.selectScenario('a05-saved');
  const saved=client.snapshot();
  assert.equal(saved.filesCount,1);
  assert.equal(saved.management.history.complete,false);
  assert.equal(saved.management.history.unlistedAssociationCount,1);
  assert.deepEqual(plain(saved.management.history.entries),[]);
  assert(!saved.management.context.actions.includes('open_files'),'incomplete unlisted history grants no Files action');
  client.selectScenario('a10-reattach');
  const reattach=client.snapshot(),historyIds=reattach.management.history.entries.flatMap(e=>e.fileIds);
  assert.equal(reattach.filesCount,5);
  assert.equal(reattach.management.history.entries.length,5);
  assert.equal(historyIds.length,5);
  assert.equal(new Set(historyIds).size,5);
  assert.equal(reattach.messages.length,0);
  assert.equal(reattach.draft.fileIds.length,1);
  assert(!historyIds.includes(reattach.draft.fileIds[0]),'new private selection is uncounted');
  const survey=reattach.files.find(f=>f.id===reattach.draft.fileIds[0]);
  assert.equal(survey.name,'site-survey-photos.pdf');assert.equal(survey.mediaType,'application/pdf');assert.equal(survey.bytes,9_856_614);assert.equal(survey.availability,'private');assert.notEqual(survey.id,'fixture-file-big');
  assert.equal(reattach.files.find(f=>f.id==='fixture-file-big').availability,'deleted','fresh survey never restores the historical source');
  assert.equal(reattach.files.find(f=>f.id==='fixture-file-table').availability,'available');
  assert(reattach.files.every(f=>f.retention.expiresAt===null),'default history and fresh selection have no expiry');
  assert.equal(client.act(draftCommand('send_sample')).filesCount,6);
  client.selectScenario('a11-full');
  const full=client.snapshot();
  assert.equal(full.filesCount,3);
  assert(full.messages.every(m=>JSON.stringify(m.destination)===JSON.stringify(full.destination)),'active messages retain exact destination ownership');
  assert(full.management.history.entries.every(e=>JSON.stringify(e.destination)===JSON.stringify(full.destination)));
  assert.equal(full.management.history.entries.flatMap(e=>e.fileIds).length,3);
  assert(full.management.storage.entries.some(e=>e.destination.agentId==='bram'),'foreign request stays global only');
  assert(!full.messages.some(m=>m.destination.agentId==='bram'));
  for(const [scenario,kind] of [['a09-pdf','pdf'],['a09-image','image'],['a09-text','text'],['a09-fallback','fallback']]){
    client.selectScenario(scenario);
    const preview=client.snapshot().preview;
    assert.equal(preview.kind,kind);assert.equal(preview.payload.sample,true);assert.equal(preview.payload.representation,'authored_sample');
    assert.equal(Object.hasOwn(preview,'content'),false);assert.equal(Object.hasOwn(preview,'unavailableReason'),false);
    assert.deepEqual(Object.keys(preview.navigation).sort(),['nextPage','nextZoom','previousPage','previousZoom','zoom']);
    preview.payload.sample=false;preview.authority.actions.length=0;
    assert.equal(client.snapshot().preview.payload.sample,true,'typed preview remains detached');
    assert(client.snapshot().preview.authority.actions.includes('close_preview'));
  }
  // Every File-shaped choice carries the reviewed policy, without sharing mutable policy objects.
  client.selectScenario('a01-picker');
  const choices=client.snapshot().pickerFiles,none={generation:1,date:null,timeZone:null,deadlineAt:null,state:'none',operationId:null,removedAt:null,removalTiming:null};
  assert.equal(choices.length,3);
  for(const choice of choices){assert.deepEqual(plain(choice.retention.expiryPolicy),none);assert.equal(choice.retention.expiresAt,choice.retention.expiryPolicy.deadlineAt);}
  choices[0].retention.expiryPolicy.date='2030-11-30';choices[0].retention.expiryPolicy.generation++;
  assert.deepEqual(plain(choices[1].retention.expiryPolicy),none);
  assert.deepEqual(plain(client.snapshot().pickerFiles[0].retention.expiryPolicy),none);
  const selected=client.act(draftCommand('add_sample_files',{fileIds:['fixture-file-plan']}));
  assert.deepEqual(plain(selected.files.find(f=>f.id===selected.draft.fileIds[0]).retention.expiryPolicy),none);
  client.selectScenario('a08-compare');
  const answer=client.snapshot().officerAnswer;
  assert(Number.isSafeInteger(answer.revision)&&answer.revision>0);
  for(const citation of answer.citations){
    if(citation.kind==='upload'){
      assert.equal(citation.navigation.kind,'preview');
      assert.equal(citation.navigation.authority.kind,'citation');
      assert(citation.navigation.authority.actions.includes('open_citation'));
      assert.equal(citation.navigation.citationTarget.answerRevision,answer.revision);
      assert.equal(citation.navigation.citationTarget.answerId,answer.id);
    }else assert.deepEqual(plain(citation.navigation),{kind:'unavailable',reason:'fixture_activity_only'});
  }
  const broken={schemaVersion:1,fixture:true,enabled:true,snapshot:()=>({schemaVersion:1,fixture:false,enabled:true}),selectScenario(){},act(){}};
  assert.throws(()=>create({enabled:true,search:'?demo',fixture:broken}).snapshot(),/Unsupported/);
  assert.throws(()=>client.selectScenario('not-a-scenario'));
  console.log('attachments client: gate, isolation, canonical actions and invalid snapshots passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
